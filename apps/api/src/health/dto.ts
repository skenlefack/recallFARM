import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsIn, IsInt, IsNumber, IsObject, IsOptional, IsPositive, IsString, IsUUID, Matches, MaxLength, Min, ValidateNested,
} from 'class-validator';
import { PageQuery } from '../common/pagination';

const DATE = /^\d{4}-\d{2}-\d{2}$/;

export class MoneyDto {
  @ApiProperty({ example: 2500 }) @IsInt() @Min(0) amount_minor: number;
  @ApiProperty({ example: 'XAF' }) @Matches(/^[A-Z]{3}$/) currency: string;
}

export class ConsumeStockDto {
  @ApiProperty({ example: 'vaccin_newcastle' }) @IsString() item_id: string;
  @ApiProperty({ example: 1 }) @IsNumber() @IsPositive() quantity: number;
}

export class HealthEventCommonDto {
  @ApiPropertyOptional() @IsOptional() @IsString() disease?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(200) product?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(100) product_batch_no?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() dose_route?: string;
  @ApiPropertyOptional() @IsOptional() @Matches(DATE) next_due?: string;
  @ApiPropertyOptional() @IsOptional() @Matches(DATE) withdrawal_meat_until?: string;
  @ApiPropertyOptional() @IsOptional() @Matches(DATE) withdrawal_milk_until?: string;
  @ApiPropertyOptional() @IsOptional() @Matches(DATE) withdrawal_eggs_until?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() protocol_id?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() protocol_step?: string;
  @ApiPropertyOptional({ type: MoneyDto }) @IsOptional() @ValidateNested() @Type(() => MoneyDto) cost?: MoneyDto;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(200) performed_by?: string;
  @ApiPropertyOptional() @IsOptional() @IsUUID() campaign_id?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() active_substance_code?: string;
  @ApiPropertyOptional() @IsOptional() @IsNumber() quantity_value?: number;
  @ApiPropertyOptional() @IsOptional() @IsString() quantity_unit?: string;
  @ApiPropertyOptional() @IsOptional() @IsInt() doses_count?: number;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(2000) notes?: string;
  @ApiPropertyOptional({ type: ConsumeStockDto }) @IsOptional() @ValidateNested() @Type(() => ConsumeStockDto) consume_stock?: ConsumeStockDto;
  @ApiPropertyOptional({ type: 'object', additionalProperties: true }) @IsOptional() @IsObject() attributes?: Record<string, unknown>;
}

const EVENT_TYPE_ENUM = ['vaccination', 'traitement', 'deparasitage', 'vitamines', 'desinfection', 'depistage', 'soin_neonatal'];

export class HealthEventBodyDto extends HealthEventCommonDto {
  @ApiPropertyOptional({ description: 'UUID v4 of the act to create' }) @IsOptional() @IsUUID() id?: string;
  @ApiPropertyOptional({ enum: EVENT_TYPE_ENUM }) @IsOptional() @IsString() event_type?: string;
  @ApiPropertyOptional({ example: '2026-10-27' }) @IsOptional() @Matches(DATE) event_date?: string;
}

export class CreateHealthEventDto extends HealthEventCommonDto {
  @ApiProperty({ description: 'UUID v4 generated by the client' }) @IsUUID() id: string;
  @ApiProperty({ enum: ['batch', 'dog', 'animal'] }) @IsIn(['batch', 'dog', 'animal']) subject_type: string;
  @ApiProperty() @IsUUID() subject_id: string;
  @ApiProperty({ enum: EVENT_TYPE_ENUM }) @IsString() event_type: string;
  @ApiProperty({ example: '2026-10-27' }) @Matches(DATE) event_date: string;
}

export class HealthEventsQuery extends PageQuery {
  @ApiPropertyOptional({ enum: ['batch', 'dog', 'animal'] }) @IsOptional() @IsIn(['batch', 'dog', 'animal']) subject_type?: string;
  @ApiPropertyOptional() @IsOptional() @IsUUID() subject_id?: string;
  @ApiPropertyOptional() @IsOptional() @IsUUID() farm_id?: string;
}

export class ConfirmReminderDto {
  @ApiPropertyOptional({ type: HealthEventBodyDto, description: 'Act details (defaults: vaccination today for the reminder step)' })
  @IsOptional() @ValidateNested() @Type(() => HealthEventBodyDto) health_event?: HealthEventBodyDto;
}

export class SnoozeDto {
  @ApiProperty({ example: '2026-11-03', description: 'At most today + 14 days' }) @Matches(DATE) until: string;
}

export class CancelDto {
  @ApiProperty() @IsString() @MaxLength(500) reason: string;
}

export class RemindersQuery extends PageQuery {
  @ApiPropertyOptional() @IsOptional() @IsUUID() farm_id?: string;
  @ApiPropertyOptional({ description: 'a_venir|envoye|confirme|manque|annule|clos|ouvert, or timing en_retard|aujourdhui' })
  @IsOptional() @IsString() status?: string;
  @ApiPropertyOptional() @IsOptional() @Matches(DATE) due_before?: string;
  @ApiPropertyOptional({ enum: ['normale', 'haute', 'critique'] }) @IsOptional() @IsString() priority?: string;
}

export class ProtocolsQuery {
  @ApiPropertyOptional() @IsOptional() @IsString() species?: string;
  @ApiPropertyOptional() @IsOptional() @Matches(/^[A-Z]{2}$/) country?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() disease?: string;
  @ApiPropertyOptional() @IsOptional() @IsUUID() farm_id?: string;
}

export class TaskDto {
  @ApiProperty() @IsUUID() id: string;
  @ApiProperty() @IsString() @MaxLength(200) title: string;
  @ApiPropertyOptional() @IsOptional() @IsString() category?: string;
  @ApiProperty() @Matches(DATE) due_date: string;
  @ApiPropertyOptional() @IsOptional() @IsIn(['batch', 'dog', 'animal']) subject_type?: string;
  @ApiPropertyOptional() @IsOptional() @IsUUID() subject_id?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() template_id?: string;
  @ApiPropertyOptional({ example: 'FREQ=WEEKLY;INTERVAL=1' }) @IsOptional() @IsString() recurrence?: string;
  @ApiPropertyOptional() @IsOptional() @IsUUID() assignee_user_id?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(2000) notes?: string;
  @ApiPropertyOptional({ enum: ['a_faire', 'fait', 'annule'] }) @IsOptional() @IsIn(['a_faire', 'fait', 'annule']) status?: string;
}

export class TasksQuery {
  @ApiPropertyOptional({ enum: ['a_faire', 'fait', 'annule'] }) @IsOptional() @IsIn(['a_faire', 'fait', 'annule']) status?: string;
}

export class VerifyQuery {
  @ApiProperty() @IsString() @MaxLength(4000) payload: string;
}

export class InboxQuery {
  @ApiProperty() @IsUUID() farm_id: string;
}
